// Render block text directly to Canvas 2D context
export function drawBlockText(ctx, text, x, y, scale = 2, color = "#FAFAFA", shadowColor = "#0E0E0E") {
  const textUp = String(text).toUpperCase();
  const charW = 6 * scale;
  
  for (let idx = 0; idx < textUp.length; idx++) {
    const ch = textUp[idx];
    const pattern = BLOCK_GLYPHS[ch] || BLOCK_GLYPHS[" "];
    const ox = x + idx * charW;
    
    for (let rowI = 0; rowI < pattern.length; rowI++) {
      const rowStr = pattern[rowI];
      for (let colI = 0; colI < rowStr.length; colI++) {
        if (rowStr[colI] === "1") {
          const px = ox + colI * scale;
          const py = y + rowI * scale;
          
          if (shadowColor) {
            ctx.fillStyle = shadowColor;
            ctx.fillRect(px + scale, py + scale, scale, scale);
          }
          ctx.fillStyle = color;
          ctx.fillRect(px, py, scale, scale);
        }
      }
    }
  }
}

